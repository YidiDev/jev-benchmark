"""The 30-question compliance/eligibility screening questionnaire used by
CT9. 27 "standard" questions (binary or small-categorical, each reducible
to a single boolean via `binary_value`) plus 3 "special" questions that
combine an instruction-following judgment (answer length) with a content-
correctness judgment, producing a genuine 4-way outcome instead of a
binary one -- see `SPECIAL_QUESTIONS` and methodology.md §13.

All ground truth here is a pure function of structured values generated by
seeded RNG (`sample_answers`) -- never the natural-language paraphrase a
form's prose expresses them in. That paraphrase is generated afterward,
in `qtree/prose_prompts.py`, and must faithfully (if colloquially) reflect
these structured values without ever making the underlying answer itself
ambiguous to a reader.
"""

