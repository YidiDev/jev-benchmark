# Per-question binary "cut" rules for multi-way standard questions -- every
# node in the tree branches on exactly one boolean, even when the
# underlying question has more than 2 possible answers.
_MULTIWAY_CUTS: dict[str, dict[str, bool]] = {
    "q03": {"0-1": False, "2-4": False, "5-9": True, "10+": True},
    "q04": {"high_school": False, "bachelors": False, "masters": True, "doctorate": True},
    "q13": {"below": False, "within": False, "above": True},
    "q14": {"immediately": True, "2_weeks": True, "1_month": False, "more_than_1_month": False},
    "q16": {"0": False, "1-5": False, "6-15": True, "16+": True},
    "q20": {"none": False, "confidential": False, "secret": True, "top_secret": True},
}


def binary_value(question_id: str, answer: str) -> bool:
    """Collapses any standard question's answer into a single boolean,
    used by every non-special tree node."""
    if question_id in _MULTIWAY_CUTS:
        return _MULTIWAY_CUTS[question_id][answer]
    return answer == "yes"


def sample_standard_answers(rng) -> dict[str, str]:
    return {q.id: rng.choices(q.options, weights=q.weights, k=1)[0] for q in STANDARD_QUESTIONS}


def sample_special_answers(rng) -> dict[str, dict[str, bool]]:
    """Returns {question_id: {"content_correct": bool, "length_compliant": bool}}
    -- the two independently-sampled bits for each special question. Roughly
    balanced (not skewed) since, unlike the word-counting design, we fully
    control these distributions."""
    out = {}
    for q in SPECIAL_QUESTIONS:
        out[q.id] = {
            "content_correct": rng.random() < 0.5,
            "length_compliant": rng.random() < 0.5,
        }
    return out


def special_outcome(content_correct: bool, length_compliant: bool) -> str:
    """The 4-way outcome key for a special question, used directly as a
    branch selector in the tree."""
    c = "correct" if content_correct else "wrong"
    l = "compliant" if length_compliant else "noncompliant"
    return f"{l}_{c}"


SPECIAL_OUTCOMES = ["compliant_correct", "compliant_wrong", "noncompliant_correct", "noncompliant_wrong"]


def sample_form_answers(form_id: str) -> dict:
    """All 30 questions' structured answers for one form, seeded uniquely
    per form so every form is an independent, reproducible draw."""
    rng = sub_rng(f"qtree_answers::{form_id}")
    return {
        "standard": sample_standard_answers(rng),
        "special": sample_special_answers(rng),
    }
